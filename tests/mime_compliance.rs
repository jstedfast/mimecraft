#[test]
fn header_and_body_positions_are_refill_independent() {
    let input = b"Subject: hello\nX: a\rb\0\n \t\n\nbody\xff\0\nlast\r\n";
    let (_, expected) = read(input, input.len());
    assert!(
        expected
            .iter()
            .any(|i| i.violation == Violation::BareCarriageReturnInHeader)
    );
    assert!(
        expected
            .iter()
            .any(|i| i.violation == Violation::BlankHeaderContinuationLine)
    );
    assert!(
        expected
            .iter()
            .any(|i| i.violation == Violation::Unexpected8BitBytesInBody)
    );
    for capacity in [1, 2, 3, 5, 17, 4096] {
        let (result, issues) = read(input, capacity);
        result.unwrap();
        assert_eq!(issues, expected, "capacity={capacity}");
    }
    for issue in expected {
        if issue.position_kind == PositionKind::Exact {
            let byte = input[issue.stream_offset as usize];
            match issue.violation {
                Violation::BareLinefeedInHeader | Violation::BareLinefeedInBody => {
                    assert_eq!(byte, b'\n')
                }
                Violation::BareCarriageReturnInHeader => assert_eq!(byte, b'\r'),
                Violation::Unexpected8BitBytesInBody => assert_eq!(byte, 0xff),
                Violation::UnexpectedNullBytesInBody => assert_eq!(byte, 0),
                _ => {}
            }
        }
    }
}

#[test]
fn delimiter_newlines_are_checked_without_entering_body_payload() {
    let input = b"Content-Type: multipart/mixed; boundary=b\r\n\r\n--b\n\r\nbody\n--b--\n";
    let (result, expected) = read(input, input.len());
    result.unwrap();
    let offsets: Vec<_> = expected
        .iter()
        .filter(|i| i.violation == Violation::BareLinefeedInBody)
        .map(|i| i.stream_offset as usize)
        .collect();
    let expected_offsets: Vec<_> = input
        .iter()
        .enumerate()
        .filter_map(|(i, &b)| (b == b'\n' && (i == 0 || input[i - 1] != b'\r')).then_some(i))
        .collect();
    assert_eq!(offsets, expected_offsets);
    for capacity in [1, 2, 7, 4096] {
        let (result, issues) = read(input, capacity);
        result.unwrap();
        assert_eq!(issues, expected);
    }
}

