use std::io::{self, BufReader, Cursor};

use mimecraft::{
    CappedMimeComplianceLogger, MimeComplianceCategories as Categories,
    MimeComplianceContext as Context, MimeComplianceIssue as Issue, MimeComplianceLogger,
    MimeComplianceOptions, MimeCompliancePositionKind as PositionKind,
    MimeComplianceSeverity as Severity, MimeComplianceViolation as Violation,
    MimeEntityParseOptions, MimeEvent, MimeParser, MimeReader,
};

fn issue(violation: Violation) -> Issue {
    Issue {
        context: Context::Transport,
        violation,
        stream_offset: 42,
        line_number: 3,
        column_number: 8,
        position_kind: PositionKind::ElementStart,
    }
}

fn read(input: &[u8], capacity: usize) -> (io::Result<()>, Vec<Issue>) {
    let source = BufReader::with_capacity(capacity, Cursor::new(input));
    let mut reader = MimeReader::new(source);
    let mut issues = Vec::new();
    let result = reader.read_entity_with_logger(
        &mut |issue| {
            issues.push(issue);
            Ok(())
        },
        |_| Ok(()),
    );
    (result, issues)
}

#[test]
fn metadata_is_complete_and_context_does_not_change_categories() {
    let mut codes = std::collections::HashSet::new();
    for violation in Violation::ALL {
        assert!(codes.insert(violation as u32));
        assert!(!violation.description().is_empty());
        assert!(!violation.remarks().is_empty());
        assert_ne!(violation.categories(), Categories::NONE);
        let transport = violation.severity(Context::Transport);
        let storage = violation.severity(Context::Storage);
        if matches!(
            violation,
            Violation::BareLinefeedInHeader
                | Violation::BareLinefeedInBody
                | Violation::OversizedLine
        ) {
            assert_eq!((transport, storage), (Severity::Major, Severity::Minor));
        } else {
            assert_eq!(transport, storage);
        }
    }
    assert_eq!(codes.len(), 91);
    for code in 1..=90 {
        assert!(codes.contains(&code));
    }
    assert!(codes.contains(&(i32::MAX as u32)));
    assert_eq!(
        Violation::RepeatedContentType.severity(Context::Transport),
        Severity::Critical
    );
    assert!(
        Violation::RepeatedContentType
            .categories()
            .contains(Categories::SECURITY | Categories::INTEROPERABILITY)
    );
    assert_eq!(
        Violation::TooManyComplianceIssues.categories(),
        Categories::SECURITY
    );
}

#[test]
fn metadata_matches_canonical_mimekit_tables() {
    fn hash(value: &str) -> u64 {
        value.bytes().fold(14695981039346656037, |hash, byte| {
            (hash ^ u64::from(byte)).wrapping_mul(1099511628211)
        })
    }
    // Generated by executing MimeKit's six compliance metadata source files.
    // Hash the full UTF-8 descriptions/remarks to catch omissions and drift.
    let expected: Vec<_> = include_str!("mime_compliance_metadata.txt")
        .lines()
        .filter(|line| !line.starts_with('#'))
        .collect();
    let actual: Vec<_> = Violation::ALL
        .into_iter()
        .map(|v| {
            format!(
                "{}\t{v:?}\t{:?}\t{:?}\t{}\t{:016x}\t{:016x}",
                v as u32,
                v.severity(Context::Transport),
                v.severity(Context::Storage),
                v.categories().bits(),
                hash(v.description()),
                hash(v.remarks())
            )
        })
        .collect();
    assert_eq!(actual, expected);
}

#[test]
fn metadata_value_positions_skip_folds_but_not_into_the_next_header() {
    for (input, violation, offset) in [
        (
            "Content-Transfer-Encoding:\r\n \tinvalid\r\n\r\n",
            Violation::InvalidContentTransferEncoding,
            30,
        ),
        (
            "Content-Transfer-Encoding: \t\r\n\r\n",
            Violation::InvalidContentTransferEncoding,
            26,
        ),
        (
            "Content-Type: multipart/mixed; boundary=b\r\nContent-Transfer-Encoding:\r\n \tbase64\r\n\r\n",
            Violation::IllegalMultipartContentTransferEncoding,
            73,
        ),
    ] {
        for capacity in [1, 2, 17, 4096] {
            let (_, issues) = read(input.as_bytes(), capacity);
            let issue = issues.iter().find(|i| i.violation == violation).unwrap();
            let prefix = &input.as_bytes()[..offset];
            let line = prefix.iter().filter(|&&b| b == b'\n').count() as u64 + 1;
            let column = prefix
                .iter()
                .rposition(|&b| b == b'\n')
                .map_or(offset + 1, |lf| offset - lf) as u64;
            assert_eq!(issue.stream_offset, offset as u64, "{input:?}");
            assert_eq!(issue.line_number, line);
            assert_eq!(issue.column_number, column);
            assert_eq!(issue.position_kind, PositionKind::Exact);
        }
    }
    let (_, issues) = read(b"Subject: x", 1);
    let issue = issues
        .iter()
        .find(|i| i.violation == Violation::IncompleteHeader)
        .unwrap();
    assert_eq!(
        (issue.stream_offset, issue.line_number, issue.column_number),
        (10, 1, 11)
    );
}

#[test]
fn accepting_logger_preserves_nested_events_and_content() {
    let input = b"Content-Type: multipart/mixed; boundary=a\r\n\r\npre\n\
        --a\r\nContent-Type: message/rfc822\r\n\r\nSubject: nested\r\n\r\none\0\xff\n\
        --a\r\nContent-Type: multipart/mixed; boundary=b\r\n\r\nnested pre\n\
        --b\r\nContent-Transfer-Encoding: binary\r\n\r\ntwo\0\xff\n\
        --b--\r\nnested end\n\
        --a--\r\nend\0\xff\n";
    for capacity in [1, 2, 5, 17, 4096] {
        let mut plain = MimeReader::new(BufReader::with_capacity(capacity, Cursor::new(input)));
        let mut logged = MimeReader::new(BufReader::with_capacity(capacity, Cursor::new(input)));
        let mut expected = Vec::new();
        let mut actual = Vec::new();
        plain
            .read_entity(|event| {
                expected.push(format!("{event:?}"));
                Ok(())
            })
            .unwrap();
        let mut issues = Vec::new();
        logged
            .read_entity_with_logger(
                &mut |issue| {
                    issues.push(issue);
                    Ok(())
                },
                |event| {
                    actual.push(format!("{event:?}"));
                    Ok(())
                },
            )
            .unwrap();
        assert_eq!(actual, expected, "capacity={capacity}");
        assert_eq!(logged.position(), plain.position());
        assert!(issues.iter().all(|i| !matches!(
            i.violation,
            Violation::MissingDate | Violation::MissingFrom | Violation::MissingMessageId
        )));
        let (_, expected_issues) = read(input, input.len());
        assert_eq!(issues, expected_issues, "capacity={capacity}");
        for issue in issues {
            let offset = issue.stream_offset as usize;
            if issue.violation == Violation::UnexpectedNullBytesInBody {
                assert_eq!(input[offset], 0);
                assert_ne!(&input[offset - 3..offset], b"two");
            }
        }
    }
}

#[test]
fn logging_preserves_source_callback_and_resource_errors() {
    struct Failing<'a>(&'a [u8]);
    impl io::Read for Failing<'_> {
        fn read(&mut self, buffer: &mut [u8]) -> io::Result<usize> {
            let input = io::BufRead::fill_buf(self)?;
            let count = buffer.len().min(input.len());
            buffer[..count].copy_from_slice(&input[..count]);
            io::BufRead::consume(self, count);
            Ok(count)
        }
    }
    impl io::BufRead for Failing<'_> {
        fn fill_buf(&mut self) -> io::Result<&[u8]> {
            if self.0.is_empty() {
                Err(io::Error::new(io::ErrorKind::BrokenPipe, "source stopped"))
            } else {
                Ok(self.0)
            }
        }
        fn consume(&mut self, count: usize) {
            self.0 = &self.0[count..];
        }
    }
    let mut parser = MimeParser::new(Failing(b"X: valid\r\n\r\nbody"));
    let error = parser
        .parse_entity_with_logger(&mut |_| Ok(()))
        .unwrap_err();
    assert_eq!(error.kind(), io::ErrorKind::BrokenPipe);
    assert_eq!(error.to_string(), "source stopped");
    let mut reader = MimeReader::new(b"\r\nbody".as_slice());
    let mut count = 0;
    let error = reader
        .read_entity_with_logger(&mut |_| Ok(()), |_| {
            count += 1;
            Err(io::Error::new(
                io::ErrorKind::PermissionDenied,
                "callback stopped",
            ))
        })
        .unwrap_err();
    assert_eq!(count, 1);
    assert_eq!(error.kind(), io::ErrorKind::PermissionDenied);
    assert_eq!(error.to_string(), "callback stopped");
    for options in [
        MimeEntityParseOptions {
            max_header_length: 5,
            ..Default::default()
        },
        MimeEntityParseOptions {
            max_input_bytes: 5,
            ..Default::default()
        },
    ] {
        let input = b"Subject: long\r\n\r\nbody".as_slice();
        let mut plain = MimeParser::with_options(input, options).unwrap();
        let mut logged = MimeParser::with_options(input, options).unwrap();
        let expected = plain.parse_entity().unwrap_err();
        let actual = logged
            .parse_entity_with_logger(&mut |_| Ok(()))
            .unwrap_err();
        assert_eq!(actual.kind(), expected.kind());
        assert_eq!(actual.to_string(), expected.to_string());
    }
}

