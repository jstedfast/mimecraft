#[test]
fn logger_errors_are_unchanged_and_poison_reader_and_parser() {
    #[derive(Debug)]
    struct Rejected;
    impl std::fmt::Display for Rejected {
        fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
            f.write_str("selected defect")
        }
    }
    impl std::error::Error for Rejected {}
    let input = b"Content-Type: text/plain\r\nContent-Type: application/octet-stream\r\n\r\nbody";
    let mut reject = |issue: Issue| {
        assert_eq!(issue.violation, Violation::RepeatedContentType);
        Err(io::Error::new(io::ErrorKind::PermissionDenied, Rejected))
    };
    let mut reader = MimeReader::new(input.as_slice());
    let mut events = 0;
    let error = reader
        .read_entity_with_logger(&mut reject, |_| {
            events += 1;
            Ok(())
        })
        .unwrap_err();
    assert_eq!(events, 0);
    assert!(error.get_ref().unwrap().is::<Rejected>());
    assert!(!reader.is_end_of_stream());
    assert_eq!(
        reader.read_entity(|_| Ok(())).unwrap_err().kind(),
        io::ErrorKind::InvalidInput
    );
    reader.replace_source(b"\r\nok".as_slice());
    reader.read_entity(|_| Ok(())).unwrap();
    let mut parser = MimeParser::new(input.as_slice());
    let error = parser.parse_entity_with_logger(&mut reject).unwrap_err();
    assert_eq!(error.kind(), io::ErrorKind::PermissionDenied);
    assert!(error.get_ref().unwrap().is::<Rejected>());
    assert_eq!(
        parser.parse_entity().unwrap_err().kind(),
        io::ErrorKind::InvalidInput
    );
}

