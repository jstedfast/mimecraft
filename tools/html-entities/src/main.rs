use std::{
    collections::BTreeMap,
    env,
    error::Error,
    fmt::{self, Write},
    fs,
    path::PathBuf,
    process::ExitCode,
};

use serde::{
    Deserialize,
    de::{self, MapAccess, Visitor},
};

type Result<T> = std::result::Result<T, Box<dyn Error>>;

const USAGE: &str = "Usage: mimecraft-html-entities [--check] [INPUT.json OUTPUT.rs]";

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Entity {
    codepoints: Vec<u32>,
    characters: String,
}

struct Entities(BTreeMap<String, Entity>);

impl<'de> Deserialize<'de> for Entities {
    fn deserialize<D: de::Deserializer<'de>>(
        deserializer: D,
    ) -> std::result::Result<Self, D::Error> {
        struct EntitiesVisitor;

        impl<'de> Visitor<'de> for EntitiesVisitor {
            type Value = Entities;

            fn expecting(&self, formatter: &mut fmt::Formatter) -> fmt::Result {
                formatter
                    .write_str("an object mapping HTML entity names to codepoints and characters")
            }

            fn visit_map<M: MapAccess<'de>>(
                self,
                mut map: M,
            ) -> std::result::Result<Entities, M::Error> {
                let mut entries = BTreeMap::new();
                while let Some((name, entity)) = map.next_entry::<String, Entity>()? {
                    // Do not let duplicate JSON keys silently replace a mapping.
                    if entries.contains_key(&name) {
                        return Err(de::Error::custom(format!("duplicate entity name: {name}")));
                    }
                    entries.insert(name, entity);
                }
                Ok(Entities(entries))
            }
        }

        deserializer.deserialize_map(EntitiesVisitor)
    }
}

fn generate(input: &str) -> Result<String> {
    let Entities(entries) = serde_json::from_str(input)?;
    if entries.is_empty() {
        return Err("entity table must not be empty".into());
    }

    let mut max_name_length = 0;
    for (name, entity) in &entries {
        // Trim the leading '&'; the runtime consumes it before matching names.
        let Some(name_without_ampersand) = name.strip_prefix('&') else {
            return Err(format!("entity name must start with '&': {name:?}").into());
        };
        let stem = name_without_ampersand
            .strip_suffix(';')
            .unwrap_or(name_without_ampersand);
        if !stem.as_bytes().first().is_some_and(u8::is_ascii_alphabetic)
            || !stem.bytes().all(|byte| byte.is_ascii_alphanumeric())
        {
            return Err(format!("invalid entity name: {name:?}").into());
        }
        let mut characters = String::new();
        for &codepoint in &entity.codepoints {
            let Some(character) = char::from_u32(codepoint) else {
                return Err(format!("invalid Unicode scalar U+{codepoint:X} in {name}").into());
            };
            characters.push(character);
        }
        if characters.is_empty() || characters != entity.characters {
            return Err(
                format!("codepoints and characters must agree and be nonempty in {name}").into(),
            );
        }
        max_name_length = max_name_length.max(name_without_ampersand.len());
    }

    // A sorted static table replaces the C# generator's transition graph.
    // Sorting makes output independent of JSON property order, and only
    // explicit input entries permit names without a semicolon.
    let mut output = String::from(concat!(
        "// Adapted from HtmlKit's CodeGenerator/Program.cs and HtmlEntities.json.\n",
        "// Copyright (C) 2026 Jeffrey Stedfast. MIT; see LICENSE.\n",
        "\n",
        "// Generated by tools\\html-entities. DO NOT EDIT.\n",
        "// Sorted, case-sensitive names omit the leading ampersand. Only the\n",
        "// explicitly listed legacy names may be decoded without a semicolon.\n",
        "\n",
    ));
    writeln!(
        output,
        "pub(super) const MAX_NAME_LENGTH: usize = {max_name_length};"
    )
    .expect("writing to a String cannot fail");
    output.push_str("\npub(super) const NAMED_ENTITIES: &[(&str, &str)] = &[\n");
    for (name, entity) in entries {
        write!(output, "    (\"{}\", \"", &name[1..]).expect("writing to a String cannot fail");
        // Emit Unicode scalars rather than UTF-16 surrogate escapes. This also
        // keeps quotes, backslashes, and controls out of the generated syntax.
        for character in entity.characters.chars() {
            write!(output, "\\u{{{:x}}}", u32::from(character))
                .expect("writing to a String cannot fail");
        }
        output.push_str("\"),\n");
    }
    output.push_str("];\n");
    Ok(output)
}

fn default_paths() -> (PathBuf, PathBuf) {
    let directory = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    (
        directory.join("HtmlEntities.json"),
        directory
            .join("..")
            .join("..")
            .join("src")
            .join("text")
            .join("html_entities.rs"),
    )
}

fn run() -> Result<()> {
    let mut args: Vec<_> = env::args_os().skip(1).collect();
    if args.len() == 1 && args[0] == "--help" {
        println!("{USAGE}");
        return Ok(());
    }
    let check = args.first().is_some_and(|argument| argument == "--check");
    if check {
        args.remove(0);
    }
    let (input, output) = match args.as_slice() {
        [] => default_paths(),
        [input, output] => (PathBuf::from(input), PathBuf::from(output)),
        _ => return Err(USAGE.into()),
    };
    let json = fs::read_to_string(&input)
        .map_err(|error| format!("cannot read {}: {error}", input.display()))?;
    let generated = generate(&json)
        .map_err(|error| format!("invalid entity data in {}: {error}", input.display()))?;

    if check {
        let actual = fs::read(&output)
            .map_err(|error| format!("cannot read {}: {error}", output.display()))?;
        if actual != generated.as_bytes() {
            return Err(format!("{} is stale; rerun without --check", output.display()).into());
        }
        println!("{} is up to date", output.display());
    } else {
        fs::write(&output, generated)
            .map_err(|error| format!("cannot write {}: {error}", output.display()))?;
        println!("Generated {}", output.display());
    }
    Ok(())
}

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("{error}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn committed_table_matches_the_bundled_input() {
        let (input, output) = default_paths();
        let json = fs::read_to_string(input).unwrap();
        let entries: Entities = serde_json::from_str(&json).unwrap();
        assert_eq!(entries.0.len(), 2231);
        assert_eq!(
            generate(&json).unwrap().as_bytes(),
            fs::read(output).unwrap()
        );
    }

    #[test]
    fn output_is_sorted_deterministic_and_uses_scalar_escapes() {
        let first = r#"{
            "&z;": {"codepoints": [128561, 38], "characters": "\ud83d\ude31&"},
            "&A": {"characters": "\"", "codepoints": [34]}
        }"#;
        let second = r#"{
            "&A": {"codepoints": [34], "characters": "\""},
            "&z;": {"characters": "\ud83d\ude31&", "codepoints": [128561, 38]}
        }"#;
        let generated = generate(first).unwrap();
        assert_eq!(generated, generate(second).unwrap());
        assert!(generated.contains("MAX_NAME_LENGTH: usize = 2;"));
        assert!(
            generated.contains("    (\"A\", \"\\u{22}\"),\n    (\"z;\", \"\\u{1f631}\\u{26}\"),")
        );
        assert!(generated.is_ascii());
        assert!(!generated.contains('\r'));
        assert!(!generated.contains("(\"A;\""));
    }

    #[test]
    fn invalid_names_and_values_are_reported() {
        for name in [
            "", "&", "&;", "amp;", "&1name;", "&a b;", "&a;;", "&a\";", "&a\\;", "&\u{e9};",
        ] {
            let input = serde_json::json!({
                name: {"codepoints": [65], "characters": "A"}
            })
            .to_string();
            assert!(generate(&input).is_err(), "{name:?}");
        }
        for input in [
            "{}",
            "[]",
            "{",
            r#"{"&a;": {"codepoints": [], "characters": ""}}"#,
            r#"{"&a;": {"codepoints": [65], "characters": "B"}}"#,
            r#"{"&a;": {"codepoints": [55296], "characters": "A"}}"#,
            r#"{"&a;": {"codepoints": [1114112], "characters": "A"}}"#,
            r#"{"&a;": {"codepoints": [-1], "characters": "A"}}"#,
            r#"{"&a;": {"codepoints": [65]}}"#,
            r#"{"&a;": {"characters": "A"}}"#,
            r#"{"&a;": {"codepoints": [65], "characters": "A", "extra": 0}}"#,
            r#"{"&a;": {"codepoints": [65], "characters": "\ud800"}}"#,
        ] {
            assert!(generate(input).is_err(), "{input}");
        }
    }

    #[test]
    fn duplicate_names_and_fields_are_rejected() {
        let input = r#"{
            "&a;": {"codepoints": [65], "characters": "A"},
            "&a;": {"codepoints": [66], "characters": "B"}
        }"#;
        assert!(
            generate(input)
                .unwrap_err()
                .to_string()
                .contains("duplicate entity name")
        );
        let input = r#"{"&a;": {"codepoints": [65], "codepoints": [66], "characters": "A"}}"#;
        assert!(generate(input).is_err());
    }
}
