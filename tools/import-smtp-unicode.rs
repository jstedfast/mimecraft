// Compile with rustc; run from the repository root with the MimeKit root argument.

use std::{env, error::Error, fmt::Write as _, fs, path::Path};

type Result<T> = std::result::Result<T, Box<dyn Error>>;

fn section<'a>(source: &'a str, start: &str, end: &str) -> Result<&'a str> {
    let rest = source
        .split_once(start)
        .ok_or_else(|| format!("missing {start}"))?
        .1;
    Ok(rest
        .split_once(end)
        .ok_or_else(|| format!("missing {end}"))?
        .0)
}

fn words(source: &str, name: &str, width: usize) -> Result<Vec<u32>> {
    let text = section(source, &format!("{name} => new byte[] {{"), "};")?;
    let bytes: Vec<u8> = text
        .split(',')
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .map(|s| {
            u8::from_str_radix(s.strip_prefix("0x").ok_or("not a hex byte")?, 16)
                .map_err(Into::into)
        })
        .collect::<Result<_>>()?;
    if bytes.len() % width != 0 {
        return Err(format!("unaligned {name}").into());
    }
    Ok(bytes
        .chunks_exact(width)
        .map(|chunk| {
            chunk
                .iter()
                .enumerate()
                .fold(0, |word, (i, byte)| word | u32::from(*byte) << (8 * i))
        })
        .collect())
}

fn array(out: &mut String, name: &str, values: &[u32], kind: &str) -> Result<()> {
    writeln!(
        out,
        "#[rustfmt::skip]\npub(crate) static {name}: &[{kind}] = &["
    )?;
    for line in values.chunks(8) {
        out.push_str("    ");
        for value in line {
            write!(out, "0x{value:08x}, ")?;
        }
        out.pop();
        out.push('\n');
    }
    out.push_str("];\n\n");
    Ok(())
}

fn check_ranges(values: &[u32], shift: u32) -> Result<()> {
    if values.first().is_none_or(|value| value >> shift != 0)
        || values
            .windows(2)
            .any(|pair| pair[0] >> shift >= pair[1] >> shift)
        || values.last().is_some_and(|value| value >> shift > 0x10ffff)
    {
        return Err("invalid Unicode range table".into());
    }
    Ok(())
}

fn tables(root: &Path) -> Result<()> {
    let utils = root.join("MimeKit").join("Utils");
    let source = fs::read_to_string(utils.join("SmtpUtf8AddressValidator.g.cs"))?;
    let norm = fs::read_to_string(utils.join("UnicodeNormalization.g.cs"))?;
    let version = section(&source, "UnicodeVersion = \"", "\"")?;
    if version != section(&norm, "UnicodeVersion = \"", "\"")? {
        return Err("Unicode snapshots must have identical versions".into());
    }
    let mut out = String::from(
        "// Adapted from MimeKit's Utils/SmtpUtf8AddressValidator.g.cs and UnicodeNormalization.g.cs.\n\
         // Copyright (C) 2026 Jeffrey Stedfast. MIT; see LICENSE.\n\
         // Derived Unicode data: Copyright (C) 1991-2026 Unicode, Inc.; see LICENSE-Unicode.\n\
         // Generated by tools/import-smtp-unicode.rs. DO NOT EDIT.\n\n",
    );
    writeln!(
        out,
        "/// Unicode snapshot shared by SMTPUTF8 policy and NFC validation.\n\
        pub const UNICODE_VERSION: &str = \"{version}\";\n"
    )?;
    let scripts = section(&source, "internal enum UnicodeScript : ushort", "}")?;
    for (index, script) in scripts
        .split_once('{')
        .ok_or("missing enum body")?
        .1
        .split(',')
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .enumerate()
    {
        if [
            "Unknown",
            "Common",
            "Inherited",
            "Latin",
            "Greek",
            "Hebrew",
            "Han",
            "Hiragana",
            "Katakana",
            "Hangul",
            "Bopomofo",
        ]
        .contains(&script)
        {
            writeln!(
                out,
                "pub(crate) const {}: u32 = {index};",
                script.to_ascii_uppercase()
            )?;
        }
    }
    out.push('\n');
    for (text, original, name, shift, comment) in [
        (
            &source,
            "CodePointData",
            "CODE_POINTS",
            11,
            "(firstCodePoint << 11) | (UnicodeScript << 2) | PrecisClass",
        ),
        (
            &source,
            "JoiningData",
            "JOINING",
            4,
            "(firstCodePoint << 4) | (isVirama << 3) | JoiningType",
        ),
        (
            &norm,
            "NormalizationData",
            "NORMALIZATION",
            10,
            "(firstCodePoint << 10) | (NFC_Quick_Check << 8) | Canonical_Combining_Class",
        ),
    ] {
        let values = words(text, original, 4)?;
        let count: usize = section(text, &format!("{original}Count = "), ";")?.parse()?;
        if values.len() != count {
            return Err(format!("{original}: count mismatch").into());
        }
        check_ranges(&values, shift)?;
        writeln!(
            out,
            "// {comment}.\n\
            // Each entry applies up to (but not including) the next entry's first code point.\n\
            // Upstream little-endian words are represented as native Rust integers."
        )?;
        array(&mut out, name, &values, "u32")?;
    }
    let compositions = words(&norm, "CompositionData", 4)?;
    let pairs = words(&norm, "CompositionPairs", 2)?;
    let count: usize = section(&norm, "CompositionCount = ", ";")?.parse()?;
    if compositions.len() != count * 3 || pairs.len() != count {
        return Err("composition count mismatch".into());
    }
    let triples: Vec<_> = compositions.chunks_exact(3).collect();
    if triples.windows(2).any(|p| p[0][0] >= p[1][0])
        || pairs.iter().any(|&i| i as usize >= count)
        || pairs
            .windows(2)
            .any(|p| triples[p[0] as usize][1..] >= triples[p[1] as usize][1..])
    {
        return Err("invalid composition ordering".into());
    }
    out.push_str(
        "// Primary composites excluding Hangul: (composite, first, second), sorted by composite.\n\
        #[rustfmt::skip]\npub(crate) static COMPOSITIONS: &[[u32; 3]] = &[\n",
    );
    for t in triples {
        writeln!(out, "    [0x{:x}, 0x{:x}, 0x{:x}],", t[0], t[1], t[2])?;
    }
    out.push_str("];\n\n// Indices into COMPOSITIONS, sorted by (first, second).\n");
    array(&mut out, "COMPOSITION_PAIRS", &pairs, "u16")?;
    fs::write(
        Path::new("src").join("smtp_utf8_data.rs"),
        format!("{}\n", out.trim_end()),
    )?;
    Ok(())
}

// Decode C# string literals without changing Unicode or quoted-pair spelling.
// Lone UTF-16 surrogates cannot be represented by Rust &str and are omitted.
fn csharp_string(literal: &str) -> Result<Option<String>> {
    let mut chars = literal.chars();
    if chars.next() != Some('"') {
        return Err("expected string literal".into());
    }
    let mut value = String::new();
    while let Some(ch) = chars.next() {
        match ch {
            '"' => return Ok(Some(value)),
            '\\' => {
                let escape = chars.next().ok_or("truncated escape")?;
                let decoded = match escape {
                    '\\' | '"' | '\'' => escape,
                    'n' => '\n',
                    'r' => '\r',
                    't' => '\t',
                    '0' => '\0',
                    'b' => '\x08',
                    'f' => '\x0c',
                    'u' | 'U' => {
                        let hex: String = chars
                            .by_ref()
                            .take(if escape == 'u' { 4 } else { 8 })
                            .collect();
                        let cp = u32::from_str_radix(&hex, 16)?;
                        if (0xd800..=0xdfff).contains(&cp) {
                            return Ok(None);
                        }
                        char::from_u32(cp).ok_or("invalid scalar")?
                    }
                    _ => return Err(format!("unsupported escape {escape}").into()),
                };
                value.push(decoded);
            }
            _ => value.push(ch),
        }
    }
    Err("unterminated string".into())
}

fn cases(root: &Path) -> Result<()> {
    let text = fs::read_to_string(
        root.join("UnitTests")
            .join("Utils")
            .join("SmtpUtf8AddressValidatorTests.cs"),
    )?;
    let mut out = String::from(
        "// Adapted from MimeKit's UnitTests/Utils/SmtpUtf8AddressValidatorTests.cs.\n\
         // Includes Arnt Gulbrandsen's mailmaint-smtputf8 test vectors, as attributed upstream.\n\
         // Copyright (C) 2026 Jeffrey Stedfast. MIT; see LICENSE.\n\
         // Generated by tools/import-smtp-unicode.rs. DO NOT EDIT.\n\n\
         // (upstream group, address, decode_idn, ascii_is_latin, expected error)\n\
         #[rustfmt::skip]\n\
         pub const CASES: &[(&str, &str, bool, bool, Option<&str>)] = &[\n",
    );
    let mut pending = Vec::new();
    let mut count = 0;
    let mut omitted = 0;
    for line in text.lines().map(str::trim) {
        if let Some(rest) = line.strip_prefix("[TestCase (") {
            pending.push(rest);
        }
        if let Some(method) = line.strip_prefix("public void ") {
            let name = method.split_once(' ').ok_or("missing method name")?.0;
            if name == "TestLabelLengthBoundary" {
                pending.clear();
                continue;
            }
            for case in pending.drain(..) {
                let Some(address) = csharp_string(case)? else {
                    omitted += 1;
                    continue;
                };
                let expected = if let Some((_, rest)) = case.split_once("SmtpUtf8AddressError.") {
                    rest.split([',', ')'])
                        .next()
                        .ok_or("missing expected error")?
                } else {
                    match name {
                        "TestSyntaxErrors" => "Syntax",
                        "TestALabels" => "ALabel",
                        "TestDisallowedCodePoints" => "DisallowedCodePoint",
                        "TestMixedScripts" => "MixedScripts",
                        "TestValidAddresses"
                        | "TestNeutralScripts"
                        | "TestCjkScriptFamilies"
                        | "TestAsciiIgnoredByDefault" => "None",
                        _ => return Err(format!("unrecognized fixture group {name}").into()),
                    }
                };
                let decode = matches!(name, "TestDecodeIdn" | "TestSpoofDetection");
                let latin = matches!(name, "TestAsciiIsLatin" | "TestSpoofDetection");
                let error = if expected == "None" {
                    "None".into()
                } else {
                    format!("Some(\"{expected}\")")
                };
                let escaped: String = address.chars().flat_map(char::escape_default).collect();
                writeln!(
                    out,
                    "    (\"{name}\", \"{escaped}\", {decode}, {latin}, {error}),"
                )?;
                count += 1;
            }
        }
    }
    if count < 250 || omitted != 4 || !pending.is_empty() {
        return Err("unexpected fixture counts".into());
    }
    out.push_str("];\n");
    fs::create_dir_all(Path::new("tests").join("data"))?;
    fs::write(
        Path::new("tests").join("data").join("smtp_utf8_cases.rs"),
        out,
    )?;
    println!("Imported {count} SMTPUTF8 fixtures; omitted {omitted} unrepresentable UTF-16 cases.");
    Ok(())
}

fn main() -> Result<()> {
    let root = env::args_os()
        .nth(1)
        .ok_or("usage: import-smtp-unicode <MimeKit root>")?;
    let root = Path::new(&root);
    tables(root)?;
    cases(root)?;
    Ok(())
}
